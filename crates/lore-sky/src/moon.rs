/// The moon `days` after noon on 1 January 2000, seen from the middle of
/// the Earth: its longitude and latitude along the ecliptic, in degrees,
/// and how far it is, in kilometres.
pub(crate) fn ecliptic(days: f64) -> (f64, f64, f64) {
    let t = days / 36_525.0;
    let (t2, t3, t4) = (t * t, t * t * t, t * t * t * t);
    let mean = 218.316_447_7 + 481_267.881_234_21 * t - 0.001_578_6 * t2 + t3 / 538_841.0
        - t4 / 65_194_000.0;
    let d = 297.850_192_1 + 445_267.111_403_4 * t - 0.001_881_9 * t2 + t3 / 545_868.0
        - t4 / 113_065_000.0;
    let m = 357.529_109_2 + 35_999.050_290_9 * t - 0.000_153_5 * t2 + t3 / 24_490_000.0;
    let m1 = 134.963_396_4 + 477_198.867_505_5 * t + 0.008_741_4 * t2 + t3 / 69_699.0
        - t4 / 14_712_000.0;
    let f = 93.272_095 + 483_202.017_523_3 * t - 0.003_653_9 * t2 - t3 / 3_526_000.0
        + t4 / 863_310_000.0;
    let a1 = 119.75 + 131.849 * t;
    let a2 = 53.09 + 479_264.29 * t;
    let a3 = 313.45 + 481_266.484 * t;
    // The Earth's orbit grows rounder: terms with the sun's anomaly shrink.
    let e = 1.0 - 0.002_516 * t - 0.000_007_4 * t2;
    let sin = |degrees: f64| degrees.to_radians().sin();
    let cos = |degrees: f64| degrees.to_radians().cos();
    let of_e = |times_m: i32| match times_m.abs() {
        0 => 1.0,
        1 => e,
        _ => e * e,
    };
    let argument = |row: &[i32]| {
        f64::from(row[0]) * d
            + f64::from(row[1]) * m
            + f64::from(row[2]) * m1
            + f64::from(row[3]) * f
    };
    let mut along = 3958.0 * sin(a1) + 1962.0 * sin(mean - f) + 318.0 * sin(a2);
    let mut distance = 0.0;
    for row in &LONGITUDE_AND_DISTANCE {
        let at = argument(row);
        let scale = of_e(row[1]);
        along += f64::from(row[4]) * scale * sin(at);
        distance += f64::from(row[5]) * scale * cos(at);
    }
    let mut above = -2235.0 * sin(mean)
        + 382.0 * sin(a3)
        + 175.0 * sin(a1 - f)
        + 175.0 * sin(a1 + f)
        + 127.0 * sin(mean - m1)
        - 115.0 * sin(mean + m1);
    for row in &LATITUDE {
        above += f64::from(row[4]) * of_e(row[1]) * sin(argument(row));
    }
    (
        mean.rem_euclid(360.0) + along * 1e-6,
        above * 1e-6,
        385_000.56 + distance * 1e-3,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_moon_is_where_meeus_has_it_on_12_april_1992() {
        // Meeus's example 47.a: 1992 April 12 at 0h TD, JDE 2448724.5.
        let (along, above, distance) = ecliptic(2_448_724.5 - 2_451_545.0);
        assert!((along - 133.162_655).abs() < 1e-4, "{along}");
        assert!((above + 3.229_126).abs() < 1e-4, "{above}");
        assert!((distance - 368_409.7).abs() < 0.5, "{distance}");
    }
}
